    private static let map: [String: String] = Dictionary(pairs, uniquingKeysWith: { a, _ in a })
    /// Una sola expresión con todas las frases (sin cortar palabras)
    private static let rx: NSRegularExpression? = {
        let alts = pairs.map { NSRegularExpression.escapedPattern(for: $0.0) }.joined(separator: "|")
        return try? NSRegularExpression(pattern: "(?<![\\p{L}])(?:" + alts + ")(?![\\p{L}])")
    }()
    static func translate(_ line: String) -> String {
        guard let rx = rx else { return line }
        let ns = line as NSString
        var out = "", last = 0
        for m in rx.matches(in: line, range: NSRange(location: 0, length: ns.length)) {
            out += ns.substring(with: NSRange(location: last, length: m.range.location - last))
            let k = ns.substring(with: m.range)
            out += map[k] ?? k
            last = m.range.location + m.range.length
        }
        return out + ns.substring(from: last)
    }
